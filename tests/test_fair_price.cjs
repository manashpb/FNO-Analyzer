const assert = require('node:assert/strict');
const {project, levels} = require('../frontend/fair-price.js');
assert.deepEqual(levels(100, 5, 10, 'CE', false), [100,95,110]);
assert.deepEqual(levels(100, 5, 10, 'CE', true), [100,105,90]);
assert.deepEqual(levels(100, 5, 10, 'PE', false), [100,105,90]);
assert.deepEqual(levels(100, 5, 10, 'PE', true), [100,95,110]);
assert.equal(levels(100, -1, 10, 'CE', false), null);
assert.equal(project(50, 100, 110, .5, .02, -7, 'CE'), 55);
assert.equal(project(50, 100, 110, -.5, .02, -7, 'PE'), 45);
assert.equal(project(50, 100, 100, .5, .02, -7, 'CE'), 49);
assert.equal(project(1, 100, 50, 1, 0, 0, 'CE'), 0);
for (const invalid of [null, undefined, NaN, Infinity, '0.5']) assert.equal(project(50,100,110,invalid,.02,-7,'CE'), null);
assert.equal(project(50,100,110,-.5,.02,-7,'CE'), null);
assert.equal(project(50,100,110,.5,.02,-7,'PE'), null);
assert.equal(project(50,100,110,.5,-.02,-7,'CE'), null);
assert.equal(project(50,100,-1,.5,.02,-7,'CE'), null);
assert.equal(project(null,null,110,null,null,null,'CE',true,100), 10);
assert.equal(project(null,null,90,null,null,null,'PE',true,100), 10);
console.log('Fair price formula and buy/sell direction tests passed');
